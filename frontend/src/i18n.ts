const UI_TEXT_ENTRIES = Object.entries(UI_TEXT).sort(([left], [right]) => right.length - left.length);
const UI_TEXT_REVERSE: Record<string, string> = Object.entries(UI_TEXT).reduce<Record<string, string>>(
  (translations, [english, chinese]) => {
    if (!(chinese in translations)) translations[chinese] = english;
    return translations;
  },
  {},
);
const UI_TEXT_REVERSE_ENTRIES = Object.entries(UI_TEXT_REVERSE).sort(([left], [right]) => right.length - left.length);

export type InterfaceLanguage = "zh-CN" | "en";

function translateText(value: string, language: InterfaceLanguage): string {
  let result = value;
  const entries = language === "zh-CN" ? UI_TEXT_ENTRIES : UI_TEXT_REVERSE_ENTRIES;
  for (const [source, target] of entries) {
    if (result === source) {
      return target;
    }
  }
  if (language === "en") {
    return result;
  }
  const nodeEdgeSummary = result.match(/^(\d[\d,]*) nodes · (\d[\d,]*) edges$/);
  if (nodeEdgeSummary) {
    return `${nodeEdgeSummary[1]} 个节点 · ${nodeEdgeSummary[2]} 条关系`;
  }
  const stageProgress = result.match(/^(\d[\d,]*)\s*\/\s*(\d[\d,]*)\s+in current stage$/);
  if (stageProgress) {
    return `${stageProgress[1]} / ${stageProgress[2]} 当前阶段`;
  }
  const nodeProgress = result.match(/^(\d[\d,]*)\s*\/\s*(\d[\d,]*)\s+nodes$/);
  if (nodeProgress) {
    return `${nodeProgress[1]} / ${nodeProgress[2]} 个节点`;
  }
  const relationshipProgress = result.match(/^(\d[\d,]*)\s*\/\s*(\d[\d,]*)\s+relationships$/);
  if (relationshipProgress) {
    return `${relationshipProgress[1]} / ${relationshipProgress[2]} 条关系`;
  }
  const activeCount = result.match(/^(\d[\d,]*) active$/);
  if (activeCount) {
    return `${activeCount[1]} 个有效条目`;
  }
  const directNeighbors = result.match(/^(\d[\d,]*) direct neighbors highlighted$/);
  if (directNeighbors) {
    return `已高亮 ${directNeighbors[1]} 个直接相关条目`;
  }
  const focusedNodes = result.match(/^(\d[\d,]*) nodes in focused view$/);
  if (focusedNodes) {
    return `聚焦视图中有 ${focusedNodes[1]} 个条目`;
  }
  const collapsedNeighbors = result.match(/^(\d[\d,]*) visible neighbors, (\d[\d,]*) collapsed$/);
  if (collapsedNeighbors) {
    return `显示 ${collapsedNeighbors[1]} 个相关条目，收起 ${collapsedNeighbors[2]} 个`;
  }
  const resultCount = result.match(/^(\d[\d,]*) results?$/);
  if (resultCount) {
    return `${resultCount[1]} 条结果`;
  }
  const sourceFieldCount = result.match(/^(\d[\d,]*) source fields$/);
  if (sourceFieldCount) {
    return `${sourceFieldCount[1]} 项来源信息`;
  }
  const candidateLinkCount = result.match(/^(\d[\d,]*) candidate links$/);
  if (candidateLinkCount) {
    return `${candidateLinkCount[1]} 个可能的联系`;
  }
  const loadingNodes = result.match(/^Loading nodes (\d[\d,]*) of (\d[\d,]*)$/);
  if (loadingNodes) {
    return `正在加载节点：${loadingNodes[1]} / ${loadingNodes[2]}`;
  }
  const loadingEdges = result.match(/^Loading edges (\d[\d,]*) of (\d[\d,]*)$/);
  if (loadingEdges) {
    return `正在加载关系：${loadingEdges[1]} / ${loadingEdges[2]}`;
  }
  const typeCount = result.match(/^(\d[\d,]*) types$/);
  if (typeCount) {
    return `${typeCount[1]} 种类型`;
  }
  const relationshipTypeCount = result.match(/^(\d[\d,]*) rel\. types$/);
  if (relationshipTypeCount) {
    return `${relationshipTypeCount[1]} 种关系类型`;
  }
  const vocabularyCount = result.match(/^(\d[\d,]*) vocabulary schemes loaded$/);
  if (vocabularyCount) {
    return `已加载 ${vocabularyCount[1]} 个词汇体系`;
  }
  const eventCount = result.match(/^(\d[\d,]*) events$/);
  if (eventCount) {
    return `${eventCount[1]} 条事件`;
  }
  const stage = result.match(/^Stage\s*(\d+)\s*\/\s*(\d+)$/);
  if (stage) {
    return `阶段 ${stage[1]}/${stage[2]}`;
  }
  const fetchFailure = result.match(/^Fetch failed:\s*(\d+)$/);
  if (fetchFailure) {
    return `请求失败：${fetchFailure[1]}`;
  }
  if (/\bnodes\b/.test(result)) {
    result = result.replace(/\bnodes\b/g, "节点");
  }
  if (/\bedges\b/.test(result)) {
    result = result.replace(/\bedges\b/g, "关系");
  }
  if (/\brelationships\b/.test(result)) {
    result = result.replace(/\brelationships\b/g, "关系");
  }
  if (result.startsWith("Stage")) {
    result = result.replace(/^Stage/, "阶段");
  }
  if (result.startsWith("Runtime layout")) {
    result = result.replace(/^Runtime layout/, "运行时布局");
  }
  if (result.startsWith("Temporal Scrubber")) {
    return result.replace("Temporal Scrubber", "时间滑块");
  }
  if (result.startsWith("Time: ")) {
    return `时间：${result.slice("Time: ".length)}`;
  }
  return result;
}

function translateElement(element: Element, language: InterfaceLanguage): void {
  const blocked = new Set(["CODE", "PRE", "SCRIPT", "STYLE", "TEXTAREA"]);
  if (blocked.has(element.tagName) || element.closest("[data-no-i18n='true']")) {
    return;
  }

  const attributes = ["title", "aria-label", "placeholder", "alt"];
  for (const attribute of attributes) {
    const value = element.getAttribute(attribute);
    if (value) {
      const translated = translateText(value, language);
      if (translated !== value) {
        element.setAttribute(attribute, translated);
      }
    }
  }

  for (const child of Array.from(element.childNodes)) {
    if (child.nodeType === Node.TEXT_NODE) {
      const value = child.nodeValue ?? "";
      const translated = translateText(value.trim(), language);
      if (translated !== value.trim()) {
        child.nodeValue = value.replace(value.trim(), translated);
      }
    } else if (child.nodeType === Node.ELEMENT_NODE) {
      translateElement(child as Element, language);
    }
  }
}

export function installInterfaceLanguage(language: InterfaceLanguage): () => void {
  document.documentElement.lang = language;
  document.title = language === "zh-CN"
    ? "港中深数据科学学院知识图谱 · Semantica Explorer"
    : "CUHK-Shenzhen School of Data Science Knowledge Graph · Semantica Explorer";
  translateElement(document.body, language);

  const observer = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      if (mutation.type === "characterData") {
        const parent = mutation.target.parentElement;
        if (parent) {
          translateElement(parent, language);
        }
        continue;
      }
      if (mutation.type === "attributes") {
        translateElement(mutation.target as Element, language);
        continue;
      }
      for (const node of Array.from(mutation.addedNodes)) {
        if (node.nodeType === Node.ELEMENT_NODE) {
          translateElement(node as Element, language);
        }
      }
    }
  });
  observer.observe(document.body, {
    attributes: true,
    attributeFilter: ["title", "aria-label", "placeholder", "alt"],
    characterData: true,
    childList: true,
    subtree: true,
  });
  return () => observer.disconnect();
}
